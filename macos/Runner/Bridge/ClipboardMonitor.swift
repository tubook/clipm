import Cocoa
import FlutterMacOS

final class ClipboardMonitor {
    static let internalMarkerType = NSPasteboard.PasteboardType("org.clipm.InternalWrite")

    /// Password manager & transient pasteboard markers that must never be recorded.
    private static let concealedTypes: Set<NSPasteboard.PasteboardType> = [
        NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType"),
        NSPasteboard.PasteboardType("org.nspasteboard.TransientType"),
        NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType"),
        NSPasteboard.PasteboardType("com.agilebits.onepassword"),
        internalMarkerType,
    ]

    private let pasteboard = NSPasteboard.general
    private var timer: Timer?
    private var lastChangeCount: Int
    private var ignoredChangeCount: Int?
    private let onClipboardChanged: ([String: Any]) -> Void

    init(onClipboardChanged: @escaping ([String: Any]) -> Void) {
        self.lastChangeCount = pasteboard.changeCount
        self.onClipboardChanged = onClipboardChanged
    }

    func start() {
        stop()
        lastChangeCount = pasteboard.changeCount
        let t = Timer.scheduledTimer(withTimeInterval: 0.3, repeats: true) { [weak self] _ in
            self?.checkPasteboard()
        }
        t.tolerance = 0.1
        RunLoop.main.add(t, forMode: .common)
        timer = t
    }

    func stop() {
        timer?.invalidate()
        timer = nil
    }

    /// Writes history item back to NSPasteboard with dual loop prevention
    /// (changeCount tracking + custom org.clipm.InternalWrite marker).
    func writeToPasteboard(
        type: String,
        plainText: String?,
        richContent: String?,
        imageBytes: Data?
    ) {
        pasteboard.clearContents()

        switch type {
        case "image":
            if let data = imageBytes {
                pasteboard.setData(data, forType: .png)
            }
        case "richText":
            if let html = richContent {
                pasteboard.setString(html, forType: .html)
            }
            if let text = plainText {
                pasteboard.setString(text, forType: .string)
            }
        default:
            if let text = plainText {
                pasteboard.setString(text, forType: .string)
            }
        }

        pasteboard.setData(Data(), forType: Self.internalMarkerType)
        ignoredChangeCount = pasteboard.changeCount
        lastChangeCount = pasteboard.changeCount
    }

    private func checkPasteboard() {
        let currentCount = pasteboard.changeCount
        guard currentCount != lastChangeCount else { return }
        lastChangeCount = currentCount

        if let ignored = ignoredChangeCount, ignored == currentCount {
            ignoredChangeCount = nil
            return
        }

        guard let types = pasteboard.types, !types.isEmpty else { return }

        let typeSet = Set(types)
        if !typeSet.isDisjoint(with: Self.concealedTypes) {
            return
        }

        let sourceApp = NSWorkspace.shared.frontmostApplication?.localizedName

        // Avoid capturing Finder file icons (TIFF + fileURL) as images.
        let isFileURL = typeSet.contains(.fileURL)
        if !isFileURL, (typeSet.contains(.png) || typeSet.contains(.tiff)) {
            if let imagePayload = extractImagePayload(sourceApp: sourceApp) {
                onClipboardChanged(imagePayload)
                return
            }
        }

        if let html = pasteboard.string(forType: .html),
           let plain = pasteboard.string(forType: .string),
           !plain.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            onClipboardChanged([
                "type": "richText",
                "plainText": plain,
                "richContent": html,
                "sourceApp": sourceApp as Any,
            ])
            return
        }

        if let plain = pasteboard.string(forType: .string), !plain.isEmpty {
            onClipboardChanged([
                "type": "text",
                "plainText": plain,
                "sourceApp": sourceApp as Any,
            ])
        }
    }

    private func extractImagePayload(sourceApp: String?) -> [String: Any]? {
        let rawData: Data?
        if let png = pasteboard.data(forType: .png) {
            rawData = png
        } else if let tiff = pasteboard.data(forType: .tiff),
                  let rep = NSBitmapImageRep(data: tiff) {
            rawData = rep.representation(using: .png, properties: [:])
        } else {
            rawData = nil
        }

        guard let pngData = rawData,
              let rep = NSBitmapImageRep(data: pngData),
              rep.pixelsWide > 0, rep.pixelsHigh > 0 else {
            return nil
        }

        return [
            "type": "image",
            "imageBytes": FlutterStandardTypedData(bytes: pngData),
            "imageWidth": rep.pixelsWide,
            "imageHeight": rep.pixelsHigh,
            "sourceApp": sourceApp as Any,
        ]
    }
}
